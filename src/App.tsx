import { useCallback, useId, useState, type KeyboardEvent } from "react";
import ReportView from "./ReportView";
import SimulatorView from "./SimulatorView";

type TabId = "report" | "simulator";

export default function App() {
  const [tab, setTab] = useState<TabId>("report");
  const baseId = useId();
  const reportTabId = `${baseId}-tab-report`;
  const simTabId = `${baseId}-tab-simulator`;
  const reportPanelId = `${baseId}-panel-report`;
  const simPanelId = `${baseId}-panel-simulator`;

  const onKeyDown = useCallback((event: KeyboardEvent<HTMLDivElement>) => {
    if (event.key !== "ArrowRight" && event.key !== "ArrowLeft") return;
    event.preventDefault();
    setTab((t) => (t === "report" ? "simulator" : "report"));
  }, []);

  return (
    <div className="site-shell">
      <header className="site-header">
        <h1>ERCOT Climate-Resilience Investment Allocation</h1>
        <p className="site-desc">
          If $43.1B in climate-driven losses is forecast for the Texas grid by
          2050, how should a limited resilience budget be allocated across 7
          energy sources and 18 plant clusters?
        </p>
        <p className="site-attrib">
          <a href="https://orcid.org/0009-0004-7482-2346" target="_blank" rel="noreferrer">
            Tianle Liang
          </a>{" "}
          · mentored by Prof.{" "}
          <a
            href="https://scholar.google.com/citations?user=oPDVmsgAAAAJ"
            target="_blank"
            rel="noreferrer"
          >
            Michael Saunders
          </a>{" "}
          · in process of inclusion on the Stanford{" "}
          <a href="https://web.stanford.edu/group/SOL/" target="_blank" rel="noreferrer">
            Systems Optimization Laboratory (SOL)
          </a>{" "}
          page
        </p>
        <p className="site-attrib">
          Findings build on an{" "}
          <a
            href="https://papers.ssrn.com/sol3/papers.cfm?abstract_id=5400605"
            target="_blank"
            rel="noreferrer"
          >
            upstream forecasting study
          </a>
          , accepted to Elsevier <em>Energy Reports</em> and currently in the
          publication process.
        </p>
      </header>

      <div
        className="site-tabs"
        role="tablist"
        aria-label="Project views"
        onKeyDown={onKeyDown}
      >
        <button
          type="button"
          role="tab"
          id={reportTabId}
          aria-controls={reportPanelId}
          aria-selected={tab === "report"}
          tabIndex={tab === "report" ? 0 : -1}
          className={tab === "report" ? "site-tab active" : "site-tab"}
          onClick={() => setTab("report")}
        >
          Project Report
        </button>
        <button
          type="button"
          role="tab"
          id={simTabId}
          aria-controls={simPanelId}
          aria-selected={tab === "simulator"}
          tabIndex={tab === "simulator" ? 0 : -1}
          className={tab === "simulator" ? "site-tab active" : "site-tab"}
          onClick={() => setTab("simulator")}
        >
          Interactive Simulator
        </button>
      </div>

      <div
        id={reportPanelId}
        role="tabpanel"
        aria-labelledby={reportTabId}
        hidden={tab !== "report"}
        className="tab-panel tab-panel-report"
      >
        {tab === "report" ? <ReportView /> : null}
      </div>

      {/* Keep the simulator mounted so inputs/results survive tab switches. */}
      <div
        id={simPanelId}
        role="tabpanel"
        aria-labelledby={simTabId}
        hidden={tab !== "simulator"}
        className="tab-panel tab-panel-simulator"
      >
        <SimulatorView active={tab === "simulator"} />
      </div>

      <footer className="site-footer">
        <p>
          <strong>Disclosure.</strong> Report text was generated by ChatGPT
          under researcher direction from code files, documentation, and
          insights over several months. A formal writeup is in progress to be
          included on the SOL page.
        </p>
        <p>SNOPT research license granted by AMPL, Inc.</p>
      </footer>
    </div>
  );
}
